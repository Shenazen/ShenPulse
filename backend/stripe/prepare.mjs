import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { integrateStripeBackend } from './integrate.mjs';
const base = process.argv[2] || '.artifacts/stripe-payments-20261029/baseline';
const target = process.argv[3] || '.artifacts/stripe-payments-20261029/stage';
const hash = text => createHash('sha256').update(text).digest('hex');
const originals = Object.fromEntries(['payments', 'index'].map(name => [name, fs.readFileSync(path.join(base, name + '.js'), 'utf8')]));
const result = integrateStripeBackend(originals.payments, originals.index);
fs.mkdirSync(path.join(target, 'stripe'), { recursive: true });
for (const name of ['payments', 'index']) fs.writeFileSync(path.join(target, name + '.js'), result[name]);
fs.copyFileSync(new URL('./service.mjs', import.meta.url), path.join(target, 'stripe/service.mjs'));
const agency = fs.readFileSync(path.join(base, 'agency-service.mjs'), 'utf8');
const nextAgency = agency.replace("s?.paymentProvider === 'paypal' && !!s?.paypalSubscriptionId", "((s?.paymentProvider === 'paypal' && !!s?.paypalSubscriptionId) || (s?.paymentProvider === 'stripe' && !!s?.stripeSubscriptionId))").replace("tier:sub.tier,source:'paypal'", 'tier:sub.tier,source:sub.paymentProvider');
if (agency === nextAgency) throw new Error('Ancrage de comptage agence absent.');
fs.mkdirSync(path.join(target, 'agencies'), {recursive:true});
fs.writeFileSync(path.join(target, 'agencies/service.mjs'), nextAgency);
fs.writeFileSync(path.join(target, 'agency-baseline.sha256'), hash(agency));
fs.writeFileSync(path.join(target, 'baseline.json'), JSON.stringify(Object.fromEntries(Object.entries(originals).map(([key, value]) => [key + '.js', hash(value)])), null, 2));
console.log('Extension Stripe préparée : ' + target);
